function pcV2_text_(x) { return String(x == null ? '' : x).trim(); }
function pcV2_normalizedText_(x) { return pcV2_text_(x).replace(/\s+/g, ' ').normalize('NFKC'); }
function pcV2_round2_(n) { return Math.round((n + Number.EPSILON) * 100) / 100; }
function pcV2_familyForTerm_(term) {
  const m = /^Clinical\s+([1-5])$/i.exec(pcV2_text_(term));
  if (!m) throw new Error('Unrecognized clinical term: ' + term);
  return +m[1] <= 2 ? 'Clinical 1-2' : 'Clinical 3-5';
}
function pcV2_expectedRubric_(family) {
  const rubric = PC_V2_RUBRICS[family];
  if (!rubric) throw new Error('Unrecognized Professional Competency rubric: ' + family);
  return rubric;
}
function pcV2_formSnapshot_(form) {
  const sections = { 'Clinical 1-2': [], 'Clinical 3-5': [] };
  let current = '';
  const all = form.getItems();
  all.forEach(function(item) {
    if (item.getType() === FormApp.ItemType.PAGE_BREAK) {
      const title = pcV2_normalizedText_(item.getTitle());
      if (/Professional Competency.*Clinical Practicum 1.*2/i.test(title)) current = 'Clinical 1-2';
      else if (/Professional Competency.*Clinical Practicum 3.*5/i.test(title)) current = 'Clinical 3-5';
      else current = '';
      return;
    }
    if (current !== '' && item.getType() === FormApp.ItemType.LIST &&
        /^Weight:\s*\d+\s*$/i.test(pcV2_text_(item.getHelpText()))) {
      sections[current].push(item);
    }
  });
  Object.keys(sections).forEach(function(family) {
    const actual = sections[family], expected = pcV2_expectedRubric_(family);
    if (actual.length !== expected.length) throw new Error('Form question count changed for ' + family +
      ': expected ' + expected.length + ', found ' + actual.length + '. No submission recorded.');
    actual.forEach(function(item, i) {
      const original = expected[i];
      const weight = Number(/^Weight:\s*(\d+)$/i.exec(pcV2_text_(item.getHelpText()))[1]);
      if (item.getId() !== original.id || weight !== original.weight ||
          pcV2_normalizedText_(item.getTitle()) !== pcV2_normalizedText_(original.title)) {
        throw new Error('Form rubric drift at ' + family + ' criterion ' + (i+1) +
          ': item ID, wording or weight changed. Review before recording a grade.');
      }
      // The earlier four-item audit did not fully confirm choice structure.
      // Accept only a standard 0,1,2,3,N/A choice set, with whitespace normalization.
      const choices = item.asListItem().getChoices().map(function(c) {return pcV2_normalizedText_(c.getValue()).toUpperCase();});
      const found = choices.slice().sort().join('|');
      const valid = ['N/A','0','1','2','3'].sort().join('|');
      if (found !== valid) {
        throw new Error('Unapproved rating choices for Form item ' + item.getId() +
          ' (' + family + '): ' + choices.join(', ') + '. Do not record an incomplete rubric.');
      }
    });
  });
  return sections;
}
function pcV2_responseAnswers_(response) {
  const byId = {}, byTitle = {};
  response.getItemResponses().forEach(function(x) {
    const item = x.getItem();
    byId[String(item.getId())] = x.getResponse();
    byTitle[pcV2_text_(item.getTitle())] = x.getResponse();
  });
  return {byId:byId,byTitle:byTitle};
}
function pcV2_calculate_(family, answers) {
  const rubric = pcV2_expectedRubric_(family);
  let points = 0, applicableWeight = 0;
  const details = rubric.map(function(item) {
    const raw = pcV2_text_(answers.byId[String(item.id)]).toUpperCase();
    if (!/^(N\/?A|[0-3])$/.test(raw))
      throw new Error('Missing/invalid rating for item ' + item.id + ': ' + raw);
    const rating = raw === 'NA' ? 'N/A' : raw;
    const applicable = rating !== 'N/A';
    const criterionPoints = applicable ? Number(rating) * item.weight : 0;
    points += criterionPoints;
    applicableWeight += applicable ? item.weight : 0;
    return {id:item.id, text:item.title, rating:rating, weight:item.weight,
      criterionScore:criterionPoints, actualWeight:applicable?item.weight:0};
  });
  if (applicableWeight <= 0) throw new Error('All Professional Competency ratings are N/A. A grade cannot be calculated.');
  const rawScore = pcV2_round2_(points / applicableWeight);
  // Approved 2026-11-05: 3.00 => 100%, 2.00=>75%, 0.00=>25%, 0.01 increments => 0.25%.
  const percentGrade = pcV2_round2_((rawScore+1)*25);
  return {rawScore:rawScore, percentGrade:percentGrade, totalCriterionScore:points,
    applicableWeight:applicableWeight, criterionCount:rubric.length, details:details, family:family};
}
// Academic rule explicitly confirmed by the program coordinator on 2026-11-05:
// individual Professional Competency evaluation PASS is 75.00% or higher.
const PC_V2_APPROVED_PASS_MIN_PERCENT = 75;
function pcV2_passResult_(percentGrade, properties) {
  const legacyConfigured = properties && typeof properties.getProperty === 'function' ?
    pcV2_text_(properties.getProperty('CCMS_PC_PASS_MIN_PERCENT')) : '';
  if (legacyConfigured && Number(legacyConfigured) !== PC_V2_APPROVED_PASS_MIN_PERCENT)
    throw new Error('Conflicting CCMS_PC_PASS_MIN_PERCENT. Approved Professional Competency threshold is 75%.');
  const pct = Number(percentGrade);
  if (!Number.isFinite(pct) || pct < 25 || pct > 100)
    throw new Error('Invalid Professional Competency percentage: ' + percentGrade);
  return pct >= PC_V2_APPROVED_PASS_MIN_PERCENT ? 'Pass' : 'Fail';
}
